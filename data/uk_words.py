def words_of_length(low: int, high: int) -> tuple[str, ...]:
    """Усі слова, довжина яких у межах [low, high]."""
    out: list[str] = []
    for words in THEMED_WORDS.values():
        out.extend(w for w in words if low <= len(w) <= high)
    return tuple(sorted(set(out)))


def category_of(word: str) -> str:
    for category, words in THEMED_WORDS.items():
        if word in words:
            return category
    return ""
